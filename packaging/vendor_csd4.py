#!/usr/bin/env python3
"""Re-vendor the CSD/4 topology catalogue into `packaging/csd4/` at a pinned
CIRISServer commit (CIRISClient#179, CIRISServer#802).

    python3 packaging/vendor_csd4.py --ref 003871fd [--src <extracted tree>]

What lands, and why each one:

* `requirements.yaml`, `topology_vocabulary.json`, `topology_vocabulary.pin`
  — BYTE copies of `harness/native/topologies/catalog/` at the commit. The card
  is compared to the first; its atoms to the second; the third is the server's
  own pin of the vocabulary to CIRISConstitution and is kept so the chain
  (card → server → constitution) is readable from here.
* `traces.json` — GENERATED by the server's own model at the same commit
  (`harness.native.model.trace` / `buildable_prefix` / `refused_steps`): each
  catalogue entry, step by step, with the atom set that holds AFTER the step.
  "Which atoms hold at one instant" is that model's answer, not a client
  re-derivation of `effects()` — a mirrored rule table drifts, and the server
  owns the model (FSD/CSD4.md, Owner). The twenty `T*.yaml` sources are not
  copied; their sha256s are recorded in `traces.json` `_meta.sources`.
* `PIN.md` — rewritten: repo, ref, commit, sha256 of every file above, and the
  refetch command. `check_csd4.py` refuses a catalogue whose bytes disagree
  with it.

Running the model executes the server's Python from the fetched tree. It runs
in a child `python3 -I` with the tree put on `sys.path` explicitly — nothing
else from the tree's directory or the current directory is importable.
Needs `gh` (for the fetch) and PyYAML (the server model loads its yaml).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

REPO = "CIRISAI/CIRISServer"
CATALOG = "harness/native/topologies/catalog"
BYTE_COPIES = ("requirements.yaml", "topology_vocabulary.json", "topology_vocabulary.pin")
OUT = Path(__file__).resolve().parent / "csd4"

#: Runs in the CHILD interpreter against the fetched tree (argv[1]).
_DUMP = r"""
import hashlib, json, sys
sys.path.insert(0, sys.argv[1])
from harness.native import model as m
cat = m.catalogue()
rep = m.evaluate(cat)
if not rep.get("ok"):
    sys.exit("the server's own model does not evaluate clean at this ref: %r" % rep.get("problems"))
entries = {}
for cid, e in sorted(cat.items(), key=lambda kv: int(kv[0][1:])):
    t = e.topology
    initial = [] if t.get("canonicals") else ["root.none"]
    entries[cid] = {
        "file": e.path.name,
        "title": e.title,
        "promises": list(e.promises),
        "initial": initial,
        "steps": [{"id": s.id, "atoms": sorted(st)} for s, st in m.trace(t)],
        "buildable_prefix": m.buildable_prefix(t),
        "refused": m.refused_steps(t),
    }
print(json.dumps({
    "_meta": {
        "catalogue_version": m.CATALOGUE_VERSION,
        "catalog_ids": m.CATALOG_IDS,
        "sources": {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                    for p in sorted(m.CATALOG_DIR.glob("T*.yaml"))},
        "generator": "packaging/vendor_csd4.py (harness.native.model.trace at the pinned commit)",
    },
    "entries": entries,
}, indent=1, sort_keys=True))
"""


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def fetch(ref: str, work: Path) -> tuple[Path, str]:
    commit = subprocess.run(["gh", "api", f"repos/{REPO}/commits/{ref}", "--jq", ".sha"],
                            check=True, capture_output=True, text=True).stdout.strip()
    tgz = work / "src.tgz"
    with tgz.open("wb") as fh:
        subprocess.run(["gh", "api", f"repos/{REPO}/tarball/{commit}"], check=True, stdout=fh)
    dest = work / "tree"
    dest.mkdir()
    with tarfile.open(tgz) as tf:
        tf.extractall(dest, filter="data")
    (root,) = list(dest.iterdir())
    return root, commit


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ref", required=True, help="CIRISServer ref (commit, branch or tag) to pin")
    ap.add_argument("--src", type=Path, help="an already-extracted tree at --ref (skips the fetch)")
    ap.add_argument("--commit", help="with --src: the full commit sha the tree is (default: resolved via gh)")
    ap.add_argument("--note", default="", help="a status line for PIN.md (e.g. 'PR #802, not on main')")
    args = ap.parse_args(argv)

    with tempfile.TemporaryDirectory(prefix="csd4-vendor-") as tmp:
        if args.src:
            root = args.src.resolve()
            commit = args.commit or subprocess.run(
                ["gh", "api", f"repos/{REPO}/commits/{args.ref}", "--jq", ".sha"],
                check=True, capture_output=True, text=True).stdout.strip()
        else:
            root, commit = fetch(args.ref, Path(tmp))
        cat = root / CATALOG
        OUT.mkdir(exist_ok=True)
        for name in BYTE_COPIES:
            shutil.copyfile(cat / name, OUT / name)
        dump = subprocess.run([sys.executable, "-I", "-c", _DUMP, str(root)],
                              check=True, capture_output=True, text=True, cwd=tmp).stdout
        (OUT / "traces.json").write_text(dump, encoding="utf-8")

    files = list(BYTE_COPIES) + ["traces.json"]
    rows = "\n".join(f"| `{f}` | `{_sha(OUT / f)}` |" for f in files)
    vocab = json.loads((OUT / "topology_vocabulary.json").read_text(encoding="utf-8"))
    vpin = dict(line.split("=", 1) for line in (OUT / "topology_vocabulary.pin").read_text().splitlines()
                if "=" in line and not line.startswith("#"))
    note = args.note or "see the PR that moved this pin"
    (OUT / "PIN.md").write_text(f"""# `packaging/csd4/` — the CSD/4 topology catalogue, pinned

Checker input for `packaging/check_csd4.py` (and, through it,
`packaging/check_csd_v3.py`). GENERATED by `packaging/vendor_csd4.py`; do not
hand-edit — the checker refuses a file whose sha256 is not the one below.

| pin | value |
|---|---|
| repo | `{REPO}` |
| ref | `{args.ref}` |
| commit | `{commit}` |
| status | {note} |
| catalogue_version | `{vocab['_meta']['catalogue_version']}` |
| atoms | {len(vocab['atoms'])} |
| vocabulary owner | `{vpin.get('repo', '?')}` @ `{vpin.get('commit', '?')}` (`{vpin.get('path', '?')}`) |

## Files

The first three are byte copies of `{CATALOG}/` at the commit;
`traces.json` is the server model's step-by-step trace of T0–T19 at the same
commit (sources' sha256 in its `_meta.sources`).

| file | sha256 |
|---|---|
{rows}

## Refetch

```
python3 packaging/vendor_csd4.py --ref <commit or tag> --note '<where the commit stands>'
```

then `python3 packaging/check_csd4.py --self-test` and every card:
`for f in FSD/CSD/CSD-*.md; do python3 packaging/check_csd_v3.py "$f" --registry client/ceg/namespace_registry.json; done`.
""", encoding="utf-8")
    print(f"vendored {REPO}@{commit[:12]} into {OUT}")
    print(rows)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
